# a. Import packages
import re
from gensim.models import Word2Vec
from nltk.corpus import stopwords

# b. Load dataset
with open("alice.txt", "r", encoding="utf-8") as file:
    text = file.read()

# c. Data preprocessing
text = re.sub(r'[^a-zA-Z. ]', ' ', text.lower())
stop_words = set(stopwords.words('english'))

sentences = []
for sentence in text.split('.'):
    words = [w for w in sentence.split()
             if w not in stop_words]
    if words:
        sentences.append(words)

# d. Generate training data
window = 2
training_data = []

for words in sentences:
    for i in range(len(words)):
        context = words[max(0, i-window):i] + words[i+1:i+window+1]
        if context:
            training_data.append((context, words[i]))

print("Sample Training Data:")
print(training_data[:5])

# e. Train CBOW model
model = Word2Vec(
    sentences,
    vector_size=50,
    window=2,
    min_count=1,
    sg=0,
    negative=5,
    epochs=20
)

# f. Find similar words
print("\nSimilar words to Alice:")
print(model.wv.most_similar('alice', topn=5))

# g. Predict output word
context_words = training_data[0][0]

print("\nContext:", context_words)
print("Actual Word:", training_data[0][1])
print("Predicted Words:")
print(model.predict_output_word(context_words, topn=5))

