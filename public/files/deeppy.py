import numpy as np
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Embedding, Lambda
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.utils import to_categorical

# a. Data preparation
corpus = [
    "deep learning models learn hierarchical representations from data",
    "neural networks process information using interconnected layers",
    "word embeddings capture semantic relationships between words"
]
tokenizer = Tokenizer()
tokenizer.fit_on_texts(corpus)
sequences = tokenizer.texts_to_sequences(corpus)
vocab_size = len(tokenizer.word_index) + 1
window_size = 2  # Context words on each side

# b. Generate training data (Context words -> Target center word)
X, y = [], []
for seq in sequences:
    for i, target in enumerate(seq):
        context = [seq[j] for j in range(max(0, i - window_size), min(len(seq), i + window_size + 1)) if j != i]
        if len(context) == window_size * 2:  # Fixed context length for clean batching
            X.append(context)
            y.append(target)

X = np.array(X)
y = to_categorical(y, num_classes=vocab_size)

# c. Train model
embed_dim = 10
model = Sequential([
    Embedding(input_dim=vocab_size, output_dim=embed_dim, input_length=window_size * 2),
    Lambda(lambda x: tf.reduce_mean(x, axis=1)),  # Averages context word embeddings
    Dense(vocab_size, activation='softmax')       # Predicts target center word
])

model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
model.fit(X, y, epochs=100, verbose=0)

# d. Output (Extract learned word embeddings & test prediction)
weights = model.get_weights()[0]
word_to_idx = tokenizer.word_index
idx_to_word = {v: k for k, v in word_to_idx.items()}

print("Embedding vector for 'neural':\n", weights[word_to_idx['neural']])

# Test predicting center word from context
sample_context = np.array([X[0]])
pred_idx = np.argmax(model.predict(sample_context, verbose=0))
print("Context:", [idx_to_word[i] for i in X[0]], "-> Predicted Target:", idx_to_word[pred_idx])

