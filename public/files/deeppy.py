# Anomaly Detection using Autoencoder

# a. Import necessary packages
import tensorflow as tf
import numpy as np

# b. Load MNIST dataset
(x_train, y_train), (x_test, y_test) = tf.keras.datasets.mnist.load_data()

# Normalize and flatten images
x_train = x_train.reshape(-1, 784) / 255.0
x_test = x_test.reshape(-1, 784) / 255.0

# Train only on normal images (digit 0)
normal_train = x_train[y_train == 0]

# c. Define Encoder
encoder = tf.keras.Sequential([
    tf.keras.layers.Input(shape=(784,)),
    tf.keras.layers.Dense(32, activation='relu')
])

# d. Define Decoder
decoder = tf.keras.Sequential([
    tf.keras.layers.Input(shape=(32,)),
    tf.keras.layers.Dense(784, activation='sigmoid')
])

# Combine Encoder and Decoder
autoencoder = tf.keras.Sequential([encoder, decoder])

# e. Compile the model
autoencoder.compile(
    optimizer='adam',
    loss='mse',
    metrics=['mae']
)

# Train the Autoencoder
autoencoder.fit(normal_train, normal_train, epochs=5, batch_size=128)

# Calculate reconstruction error on normal training images
train_reconstructed = autoencoder.predict(normal_train)
train_error = np.mean((normal_train - train_reconstructed) ** 2, axis=1)

# Set anomaly threshold
threshold = np.percentile(train_error, 95)

# Reconstruct test images
test_reconstructed = autoencoder.predict(x_test)
test_error = np.mean((x_test - test_reconstructed) ** 2, axis=1)

# Detect anomalies
predictions = test_error > threshold

# Actual labels: 0 = Normal, 1 = Anomaly
actual = y_test != 0

# Evaluate anomaly detection accuracy
accuracy = np.mean(predictions == actual)

print("Threshold:", threshold)
print("Anomaly Detection Accuracy:", accuracy)

# Display sample predictions
for i in range(10):
    print("Digit:", y_test[i],
          "Predicted:", "Anomaly" if predictions[i] else "Normal")

