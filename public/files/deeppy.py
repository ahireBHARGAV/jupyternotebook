# --------------------------------------------------

x_test_reconstructed = autoencoder.predict(x_test)


# --------------------------------------------------
# 11. Calculate reconstruction error
# --------------------------------------------------

reconstruction_error = np.mean(
    np.square(x_test - x_test_reconstructed),
    axis=1
)


